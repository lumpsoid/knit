// Builds every platform's app icon from the knotted-k geometry (knot.js), the "Two strands" concept.
// Usage: node design/icon/build_icons.mjs   (needs resvg and ImageMagick's `magick` on PATH)
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
for (const f of ['gallery.js', 'knot.js']) vm.runInThisContext(fs.readFileSync(path.join(here, f), 'utf8'), { filename: f });

const ICON = {
  bg: '#5B6CFF', stem: '#FFFFFF', strand: '#FFC4A3',
  rope: 12, gap: .75,
  // Knot height over the visible tile edge, as approved in the gallery (scale .33 on the 108 tile).
  glyph: .33 * KNOT_HEIGHT / 108,
};
// Android shows the middle 72 of the 108-unit adaptive canvas; the glyph keeps its share of what is visible.
const ADAPTIVE_VISIBLE = 72 / 108;

// Optical sizing: thin rope vanishes on small rasters, so small sizes get a heavier rope and tighter gaps.
const ropeFor = px => px <= 32 ? { rope: ICON.rope * 1.6, gap: .5 } : px <= 64 ? { rope: ICON.rope * 1.3, gap: .6 }
  : { rope: ICON.rope, gap: ICON.gap };

// Ramer-Douglas-Peucker, to keep exported paths short.
function simplify(pts, eps) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  let idx = 0, max = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = distToLine(pts[i], [a, b]);
    if (d > max) { max = d; idx = i; }
  }
  return max > eps ? [...simplify(pts.slice(0, idx + 1), eps).slice(0, -1), ...simplify(pts.slice(idx), eps)] : [a, b];
}

// The knot's strokes placed at (cx, cy), `height` tall, in the target's units.
function glyph({ cx, cy, height, rope = ICON.rope, gap = ICON.gap, mono = null }) {
  const s = height / KNOT_HEIGHT, [kx, ky] = KNOT_CENTER;
  return knotStrokes({ rope, gap }).map(({ role, pts }) => ({
    color: mono ?? (role === 'stem' ? ICON.stem : ICON.strand),
    width: f(rope * s),
    d: poly(simplify(pts, .12).map(([x, y]) => [cx + (x - kx) * s, cy + (y - ky) * s])),
  }));
}
const svgPaths = g => g.map(p => `<path d="${p.d}" ${stroke(p.color, p.width)}/>`).join('\n  ');
const svgDoc = (size, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">\n  ${body}\n</svg>\n`;

// ---------- icon shapes (each takes a pixel size, for optical sizing) ----------
const SHAPES = {
  // Full bleed, no transparency: iOS applies its own mask.
  square: n => svgDoc(n, `<rect width="${n}" height="${n}" fill="${ICON.bg}"/>
  ${svgPaths(glyph({ cx: n / 2, cy: n / 2, height: ICON.glyph * n, ...ropeFor(n) }))}`),
  // Rounded square with transparent corners: legacy Android, Windows, web, favicon.
  rounded: n => svgDoc(n, `<rect width="${n}" height="${n}" rx="${f(n * .2237)}" fill="${ICON.bg}"/>
  ${svgPaths(glyph({ cx: n / 2, cy: n / 2, height: ICON.glyph * n, ...ropeFor(n) }))}`),
  // Web maskable: full bleed, glyph kept inside the mask's safe zone like an adaptive icon.
  maskable: n => svgDoc(n, `<rect width="${n}" height="${n}" fill="${ICON.bg}"/>
  ${svgPaths(glyph({ cx: n / 2, cy: n / 2, height: ICON.glyph * ADAPTIVE_VISIBLE * n, ...ropeFor(n * ADAPTIVE_VISIBLE) }))}`),
  // macOS: Apple's grid, an 824 rounded square inset in 1024, with a soft shadow.
  macos: n => {
    const k = n / 1024, inset = 100 * k, side = 824 * k;
    return svgDoc(n, `<defs><filter id="s" x="-20%" y="-20%" width="140%" height="140%">
    <feDropShadow dx="0" dy="${f(10 * k)}" stdDeviation="${f(10 * k)}" flood-color="#000" flood-opacity=".28"/></filter></defs>
  <rect x="${inset}" y="${inset}" width="${side}" height="${side}" rx="${f(185.4 * k)}" fill="${ICON.bg}" filter="url(#s)"/>
  ${svgPaths(glyph({ cx: n / 2, cy: n / 2, height: ICON.glyph * side, ...ropeFor(side) }))}`);
  },
};

// ---------- Android adaptive layers (vector drawables, 108dp) ----------
function vectorDrawable(mono) {
  const g = glyph({ cx: 54, cy: 54, height: ICON.glyph * 72, mono });
  const paths = g.map(p => `    <path
        android:pathData="${p.d}"
        android:strokeColor="${p.color.replace('#', '#FF')}"
        android:strokeWidth="${p.width}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/build_icons.mjs. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${paths}
</vector>
`;
}

// ---------- rasterizing ----------
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'knit-icon-'));
function png(shape, n, out, { opaque = false } = {}) {
  const svg = path.join(tmp, `${shape}-${n}.svg`);
  fs.writeFileSync(svg, SHAPES[shape](n));
  fs.mkdirSync(path.dirname(out), { recursive: true });
  execFileSync('resvg', [svg, out, '-w', String(n), '-h', String(n)]);
  if (opaque) execFileSync('magick', [out, '-background', ICON.bg, '-alpha', 'remove', '-alpha', 'off', out]);
}
const sizeOf = file => +execFileSync('magick', ['identify', '-format', '%w', file]).toString();
const write = (rel, text) => { const p = path.join(root, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); };
const r = rel => path.join(root, rel);

// Masters, for reference and design tools.
for (const shape of Object.keys(SHAPES)) write(`design/icon/export/knit_icon_${shape}.svg`, SHAPES[shape](1024));
write('design/icon/export/knit_icon_foreground.svg', svgDoc(108, svgPaths(glyph({ cx: 54, cy: 54, height: ICON.glyph * 72 }))));

// Android: adaptive icon (API 26+) with a themed-icon monochrome layer, plus legacy PNGs for API 23-25.
const res = 'android/app/src/main/res';
write(`${res}/drawable/ic_launcher_foreground.xml`, vectorDrawable(null));
write(`${res}/drawable/ic_launcher_monochrome.xml`, vectorDrawable('#FFFFFF'));
write(`${res}/values/ic_launcher_background.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/build_icons.mjs. Do not edit by hand. -->
<resources>
    <color name="ic_launcher_background">${ICON.bg.replace('#', '#FF')}</color>
</resources>
`);
write(`${res}/mipmap-anydpi-v26/ic_launcher.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/build_icons.mjs. Do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`);
for (const [dpi, n] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 }))
  png('rounded', n, r(`${res}/mipmap-${dpi}/ic_launcher.png`));

// iOS and macOS: regenerate every file the asset catalogs already list, at its current size.
for (const [dir, shape, opaque] of [
  ['ios/Runner/Assets.xcassets/AppIcon.appiconset', 'square', true],
  ['macos/Runner/Assets.xcassets/AppIcon.appiconset', 'macos', false],
]) {
  for (const file of fs.readdirSync(r(dir)).filter(f => f.endsWith('.png'))) {
    const out = r(`${dir}/${file}`);
    png(shape, sizeOf(out), out, { opaque });
  }
}

// Web.
png('rounded', 16, r('web/favicon.png'));
for (const n of [192, 512]) {
  png('rounded', n, r(`web/icons/Icon-${n}.png`));
  png('maskable', n, r(`web/icons/Icon-maskable-${n}.png`));
}
const manifest = r('web/manifest.json');
fs.writeFileSync(manifest, fs.readFileSync(manifest, 'utf8').replace(/"(background_color|theme_color)": "#[0-9A-Fa-f]{6}"/g, `"$1": "${ICON.bg}"`));

// Windows: one .ico holding a hand-sized image per size.
const icoSizes = [16, 24, 32, 48, 64, 128, 256];
for (const n of icoSizes) png('rounded', n, path.join(tmp, `ico-${n}.png`));
execFileSync('magick', [...icoSizes.map(n => path.join(tmp, `ico-${n}.png`)), r('windows/runner/resources/app_icon.ico')]);

fs.rmSync(tmp, { recursive: true });
console.log('icons written');
